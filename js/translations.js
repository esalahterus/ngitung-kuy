  function getLanguage() {
    const saved = window.NgitungKuy?.Settings?.get('language');
    return saved === 'en' ? 'en' : 'id';
  }

  // Optional params: t('x', 'Fallback {n}', { n: 3 }) replaces {n} placeholders
  function t(key, fallback, params) {
    const language = getLanguage();

    const text = translations[language]?.[key]
      ?? translations.id[key]
      ?? fallback
      ?? key;

    if (!params || typeof text !== 'string') return text;
    return text.replace(/\{(\w+)\}/g, (match, name) =>
      Object.prototype.hasOwnProperty.call(params, name) ? params[name] : match);
  }

  function applyTranslations(root = document) {
    const language = getLanguage();

    document.documentElement.lang = language;

    root.querySelectorAll('[data-i18n]').forEach(element => {
      const key = element.getAttribute('data-i18n');
      element.textContent = t(key);
    });

    root.querySelectorAll('[data-i18n-attr]').forEach(element => {
      const definitions = element.getAttribute('data-i18n-attr');

      definitions.split(';').forEach(definition => {
        const [attribute, key] = definition.split(':').map(value => value.trim());

        if (attribute && key) {
          element.setAttribute(attribute, t(key));
        }
      });
    });

    root.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
      element.placeholder = t(
        element.getAttribute('data-i18n-placeholder')
      );
    });
  }

  window.NgitungKuy = window.NgitungKuy || {};
  window.NgitungKuy.I18n = {
    translations,
    getLanguage,
    t,
    applyTranslations
  };
